// Builds js/manual.js from MANUAL.md (English) and MANUAL.hu.md (Hungarian),
// so the user manual in the Help menu is the same text as the one on GitHub.
// Run it after editing either file:
//      node tools/manual-build.js
// The tool shows a markdown subset: # headings, **bold**, *italic*, `code`,
// [links](url), * / 1. lists (2 spaces = one level), | tables |, ``` code ```, ---
"use strict";
const fs=require("fs"), path=require("path");
const root=path.join(__dirname,"..");
const read=(f)=>fs.readFileSync(path.join(root,f),"utf8").replace(/\r/g,"")
	.split("\n").filter(l=>!/^\*\[.*\]\(MANUAL(\.hu)?\.md\)\*\s*$/.test(l)).join("\n");   // the language link of GitHub
const out="// GENERATED by tools/manual-build.js from MANUAL.md and MANUAL.hu.md - edit those, not this file\n"
	+"\"use strict\";\n"
	+"const SDL_MANUAL_TEXT = {\n"
	+"\ten: "+JSON.stringify(read("MANUAL.md"))+",\n"
	+"\thu: "+JSON.stringify(read("MANUAL.hu.md"))+",\n"
	+"};\n";
fs.writeFileSync(path.join(root,"js","manual.js"),out);
console.log("js/manual.js written ("+out.length+" bytes)");
